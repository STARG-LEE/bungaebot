// related 배열로부터 무방향 엣지를 생성(중복·자기참조·존재하지 않는 id 제거).
export function buildEdges(nodes = NODES) {
  const ids = new Set(nodes.map((n) => n.id))
  const seen = new Set()
  const edges = []
  for (const n of nodes) {
    for (const r of n.related || []) {
      if (!ids.has(r) || r === n.id) continue
      const key = [n.id, r].sort().join('::')
      if (seen.has(key)) continue
      seen.add(key)
      edges.push({ source: n.id, target: r })
    }
  }
  return edges
}

export const EDGES = buildEdges(NODES)

// id → node 빠른 조회
export const NODE_BY_ID = Object.fromEntries(NODES.map((n) => [n.id, n]))

// 한 노드에 직접 연결된 노드들
export function neighborsOf(id) {
  const out = []
  for (const e of EDGES) {
    if (e.source === id) out.push(NODE_BY_ID[e.target])
    else if (e.target === id) out.push(NODE_BY_ID[e.source])
  }
  return out.filter(Boolean)
}
